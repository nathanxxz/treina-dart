void main(){
  var variacao = 1; // var é uma variável que pode mudar de tipo
  print(variacao);
  const constante = 1; // const é uma variável que não pode mudar de tipo
  print(constante);
  final finalVar = 1; // final é uma variável que não pode mudar de tipo, mas pode ser inicializada depois
  print(finalVar);
}